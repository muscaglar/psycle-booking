function collectIds(htmlUnits, jsInfos, cssInfos) {
  const escRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const refs = (id) => {
    const re = new RegExp('[\'"`]' + escRe(id) + '[\'"`]|#' + escRe(id) + '(?![\\w-])');
    const js = jsInfos.filter((i) => i.lx.nocom.some((l) => l.indexOf(id) !== -1 && re.test(l))).map((i) => i.rel);
    const html = htmlUnits.filter((u) => u.nocom.some((l, k) => u.code[k].trim() && l.indexOf(id) !== -1 && re.test(l))).map((u) => u.rel + ' (inline)');
    const hexish = /^[0-9a-fA-F]{3,8}$/.test(id);
    const cre = new RegExp('#' + escRe(id) + '(?![\\w-])');
    const css = hexish ? [] : cssInfos.filter((c) => c.nocom.some((l) => l.indexOf(id) !== -1 && cre.test(l))).map((c) => c.rel.replace(/^css\//, ''));
    return { js: js.concat(html), css };
  };
  const statics = [];
  for (const u of htmlUnits) {
    u.raw.forEach((line, i) => {
      if (u.code[i].trim()) return;                                                       // inside an inline script
      const re = /(?<![\w-])id\s*=\s*"([^"]+)"/g;
      let mt;
      while ((mt = re.exec(line))) statics.push({ id: mt[1], file: u.rel, line: i + 1, ...refs(mt[1]) });
    });
  }
  const staticIds = new Set(statics.map((s) => s.id));
  const runtime = new Map();
  // The scripts, and the INLINE scripts of the shells (the update bar is built by one): `code` is blank outside them.
  const scripted = jsInfos.map((info) => ({ rel: info.rel, lines: info.lx.nocom, live: () => true }))
    .concat(htmlUnits.map((u) => ({ rel: u.rel, lines: u.nocom, live: (i) => !!u.code[i].trim() })));
  for (const unit of scripted) {
    unit.lines.forEach((line, i) => {
      if (!unit.live(i)) return;
      const res = [/(?<![\w-])id\s*=\s*\\?["']([A-Za-z][\w-]*)\\?["']/g, /\.id\s*=\s*['"]([A-Za-z][\w-]*)['"]/g, /setAttribute\(\s*['"]id['"]\s*,\s*['"]([A-Za-z][\w-]*)['"]/g];
      for (const re of res) {
        let mt;
        while ((mt = re.exec(line))) {
          if (staticIds.has(mt[1])) continue;
          if (!runtime.has(mt[1])) runtime.set(mt[1], []);
          if (!runtime.get(mt[1]).some((x) => x.file === unit.rel && x.line === i + 1)) runtime.get(mt[1]).push({ file: unit.rel, line: i + 1 });
        }
      }
    });
  }
  return { statics, runtime: [...runtime.entries()].sort((a, b) => byName(a[0].toLowerCase(), b[0].toLowerCase())).map(([id, made]) => ({ id, made, ...refs(id) })) };
}

