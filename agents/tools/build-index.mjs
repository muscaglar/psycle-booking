// Lexers — each returns per-line masks, so the regexes below never match inside a comment (or a string)
// ───────────────────────────────────────────────────────────────────────────

const REGEX_AFTER_WORD = new Set(['return', 'typeof', 'instanceof', 'in', 'of', 'new', 'delete', 'void', 'throw', 'case', 'do', 'else', 'yield', 'await']);
const isWordChar = (ch) => (ch >= 'a' && ch <= 'z') || (ch >= 'A' && ch <= 'Z') || (ch >= '0' && ch <= '9') || ch === '_' || ch === '$';

// code[i]  : line i with comments AND the contents of strings / templates / regex literals blanked (structure only)
// nocom[i] : line i with comments blanked (strings kept)
// depth[i] : open brackets ( [ { ${ at the START of line i; depth[lines] = at the end of the file
// mode[i]  : lexer mode at the start of line i ('code', 'tpl', 'bc', 'sq', 'dq')
function lexJs(src) {
  const code = [], nocom = [], depth = [0], mode = ['code'];
  const stack = [];
  let cbuf = '', nbuf = '';
  let m = 'code', inClass = false, cont = false;
  let lastType = '', lastVal = '', word = '', afterValue = false;
  const flushWord = () => { if (word) { lastType = 'word'; lastVal = word; word = ''; } };
  const isValue = () => lastType === 'value' || (lastType === 'word' && !REGEX_AFTER_WORD.has(lastVal)) || (lastType === 'punct' && (lastVal === ')' || lastVal === ']'));
  const regexAllowed = () => {
    if (!lastType) return true;
    if (lastType === 'word') return REGEX_AFTER_WORD.has(lastVal);
    if (lastType === 'value') return false;
    return !(lastVal === ')' || lastVal === ']' || lastVal === '}');
  };
  const n = src.length;
  for (let i = 0; i < n; i++) {
    const ch = src[i], nx = src[i + 1];
    if (ch === '\n') {
      flushWord();
      if (m === 'lc') m = 'code';
      else if ((m === 'sq' || m === 'dq') && !cont) m = 'code';     // unterminated string: recover
      else if (m === 're') { m = 'code'; inClass = false; }          // not a regex after all: recover
      cont = false;
      code.push(cbuf); nocom.push(nbuf); cbuf = ''; nbuf = '';
      depth.push(stack.length); mode.push(m);
      continue;
    }
    if (m === 'code') {
      if (ch === ' ' || ch === '\t') { flushWord(); cbuf += ch; nbuf += ch; continue; }
      if (isWordChar(ch)) { word += ch; cbuf += ch; nbuf += ch; continue; }
      flushWord();
      if (ch === '/' && nx === '/') { m = 'lc'; cbuf += '  '; nbuf += '  '; i++; continue; }
      if (ch === '/' && nx === '*') { m = 'bc'; cbuf += '  '; nbuf += '  '; i++; continue; }
      if (ch === '/' && regexAllowed()) { m = 're'; inClass = false; cbuf += '/'; nbuf += '/'; continue; }
      if (ch === "'") { m = 'sq'; cbuf += ch; nbuf += ch; continue; }
      if (ch === '"') { m = 'dq'; cbuf += ch; nbuf += ch; continue; }
      if (ch === '`') { m = 'tpl'; cbuf += ch; nbuf += ch; continue; }
      cbuf += ch; nbuf += ch;
      if (ch === '(' || ch === '[' || ch === '{') stack.push(ch);
      else if (ch === ')' || ch === ']' || ch === '}') {
        const want = ch === ')' ? '(' : ch === ']' ? '[' : '{';
        const top = stack[stack.length - 1];
        if (ch === '}' && top === '${') { stack.pop(); m = 'tpl'; lastType = 'punct'; lastVal = '}'; continue; }
        if (top === want) stack.pop();
        else { const at = stack.lastIndexOf(want); if (at !== -1) stack.length = at; }
      }
      if ((ch === '+' || ch === '-') && lastType === 'punct' && lastVal === ch && afterValue) { lastType = 'value'; lastVal = ''; continue; }   // x++ / 2
      afterValue = isValue();
      lastType = 'punct'; lastVal = ch;
      continue;
    }
    if (m === 'lc') { cbuf += ' '; nbuf += ' '; continue; }
    if (m === 'bc') {
      if (ch === '*' && nx === '/') { m = 'code'; cbuf += '  '; nbuf += '  '; i++; } else { cbuf += ' '; nbuf += ' '; }
      continue;
    }
    if (m === 'sq' || m === 'dq') {
      if (ch === '\\') {
        cbuf += ' '; nbuf += ch;
        if (nx === '\n') cont = true; else if (nx !== undefined) { cbuf += ' '; nbuf += nx; i++; }
        continue;
      }
      if ((m === 'sq' && ch === "'") || (m === 'dq' && ch === '"')) { m = 'code'; cbuf += ch; nbuf += ch; lastType = 'value'; lastVal = ''; continue; }
      cbuf += ' '; nbuf += ch; continue;
    }
    if (m === 'tpl') {
      if (ch === '\\') { cbuf += ' '; nbuf += ch; if (nx !== '\n' && nx !== undefined) { cbuf += ' '; nbuf += nx; i++; } continue; }
      if (ch === '`') { m = 'code'; cbuf += ch; nbuf += ch; lastType = 'value'; lastVal = ''; continue; }
      if (ch === '$' && nx === '{') { stack.push('${'); m = 'code'; cbuf += '${'; nbuf += '${'; i++; lastType = 'punct'; lastVal = '{'; continue; }
      cbuf += ' '; nbuf += ch; continue;
    }
    if (m === 're') {
      if (ch === '\\') { cbuf += ' '; nbuf += ch; if (nx !== '\n' && nx !== undefined) { cbuf += ' '; nbuf += nx; i++; } continue; }
      if (ch === '[') inClass = true;
      else if (ch === ']') inClass = false;
      else if (ch === '/' && !inClass) {
        m = 'code'; cbuf += '/'; nbuf += '/';
        while (i + 1 < n && src[i + 1] >= 'a' && src[i + 1] <= 'z') { i++; cbuf += ' '; nbuf += src[i]; }
        lastType = 'value'; lastVal = ''; continue;
      }
      cbuf += ' '; nbuf += ch; continue;
    }
  }
  flushWord();
  code.push(cbuf); nocom.push(nbuf); depth.push(stack.length);
  return { code, nocom, depth, mode, balanced: stack.length === 0 && (m === 'code' || m === 'lc') };
}

// CSS: comments (with their line spans) and the text with comments blanked.
function lexCss(src) {
  const comments = [];
  let out = '', i = 0, line = 0;
  const n = src.length;
  while (i < n) {
    if (src[i] === '/' && src[i + 1] === '*') {
      const end = src.indexOf('*/', i + 2);
      const stop = end === -1 ? n : end + 2;
      const text = src.slice(i, stop);
      const startCol = i - (src.lastIndexOf('\n', i - 1) + 1);
      const lead = src.slice(i - startCol, i);
      comments.push({ start: line, text, lineStart: /^\s*$/.test(lead) });
      for (const ch of text) { if (ch === '\n') { out += '\n'; line++; } else out += ' '; }
      comments[comments.length - 1].end = line;
      i = stop;
      continue;
    }
    if (src[i] === '\n') line++;
    out += src[i++];
  }
  return { comments, nocom: out.split('\n') };
}

// Swift: comments and string contents blanked; brace depth at the start of each line.
function lexSwift(src) {
  const code = [], depth = [0];
  let buf = '', braces = 0, bc = 0;
  const modes = ['code'];                 // code | str | mstr | interp (code inside \( … ))
  const parens = [];                      // open-paren count per interpolation
  const n = src.length;
  for (let i = 0; i < n; i++) {
    const ch = src[i], nx = src[i + 1];
    const m = modes[modes.length - 1];
    if (ch === '\n') {
      if (m === 'lc') modes.pop();
      if (modes[modes.length - 1] === 'str') modes.pop();               // unterminated: recover
      code.push(buf); buf = ''; depth.push(braces); continue;
    }
    if (m === 'lc') { buf += ' '; continue; }
    if (bc > 0) {
      if (ch === '/' && nx === '*') { bc++; buf += '  '; i++; }
      else if (ch === '*' && nx === '/') { bc--; buf += '  '; i++; }
      else buf += ' ';
      continue;
    }
    if (m === 'code' || m === 'interp') {
      if (ch === '/' && nx === '/') { modes.push('lc'); buf += '  '; i++; continue; }
      if (ch === '/' && nx === '*') { bc = 1; buf += '  '; i++; continue; }
      if (ch === '"') {
        if (nx === '"' && src[i + 2] === '"') { modes.push('mstr'); buf += '"""'; i += 2; } else { modes.push('str'); buf += '"'; }
        continue;
      }
      if (m === 'interp') {
        if (ch === '(') parens[parens.length - 1]++;
        else if (ch === ')') { if (--parens[parens.length - 1] === 0) { parens.pop(); modes.pop(); buf += ' '; continue; } }
        buf += ' '; continue;
      }
      if (ch === '{') braces++;
      else if (ch === '}') braces = Math.max(0, braces - 1);
      buf += ch; continue;
    }
    // str | mstr
    if (ch === '\\' && nx === '(') { modes.push('interp'); parens.push(1); buf += '  '; i++; continue; }
    if (ch === '\\') { buf += '  '; i++; continue; }
    if (m === 'str' && ch === '"') { modes.pop(); buf += '"'; continue; }
    if (m === 'mstr' && ch === '"' && nx === '"' && src[i + 2] === '"') { modes.pop(); buf += '"""'; i += 2; continue; }
    buf += ' ';
  }
  code.push(buf); depth.push(braces);
  return { code, depth };
}

// Java: `code` has comments AND the contents of string, character and text-block literals blanked; `nocom` has only
// the comments blanked. Both keep every column where it was.
function lexJava(src) {
  const code = [], nocom = [];
  let cbuf = '', nbuf = '', m = 'code';   // code | lc | bc | str | chr | text
  const n = src.length;
  const both = (c, w) => { cbuf += c; nbuf += w === undefined ? c : w; };
  for (let i = 0; i < n; i++) {
    const ch = src[i], nx = src[i + 1];
    if (ch === '\n') {
      if (m === 'lc' || m === 'str' || m === 'chr') m = 'code';         // a literal left open at a line end: recover
      code.push(cbuf); nocom.push(nbuf); cbuf = ''; nbuf = '';
      continue;
    }
    if (m === 'code') {
      if (ch === '/' && nx === '/') { m = 'lc'; both('  '); i++; continue; }
      if (ch === '/' && nx === '*') { m = 'bc'; both('  '); i++; continue; }
      if (ch === '"' && nx === '"' && src[i + 2] === '"') { m = 'text'; both('"""'); i += 2; continue; }
      if (ch === '"') { m = 'str'; both(ch); continue; }
      if (ch === "'") { m = 'chr'; both(ch); continue; }
      both(ch); continue;
    }
    if (m === 'lc') { both(' '); continue; }
    if (m === 'bc') {
      if (ch === '*' && nx === '/') { m = 'code'; both('  '); i++; } else both(' ');
      continue;
    }
    if (ch === '\\') { both(' ', ch); if (nx !== undefined && nx !== '\n') { both(' ', nx); i++; } continue; }
    if (m === 'str' && ch === '"') { m = 'code'; both(ch); continue; }
    if (m === 'chr' && ch === "'") { m = 'code'; both(ch); continue; }
    if (m === 'text' && ch === '"' && nx === '"' && src[i + 2] === '"') { m = 'code'; both('"""'); i += 2; continue; }
    both(' ', ch);
  }
  code.push(cbuf); nocom.push(nbuf);
  return { code, nocom };
}

// An HTML shell: inline <script> bodies go through the JS lexer; everything else stays as written in `nocom`
// (ids are read from it) and is blanked in `code`.
function lexHtml(src) {
  const raw = src.split('\n');
  const codeChars = src.replace(/[^\n]/g, ' ').split('');
  const nocomChars = src.split('');
  const re = /<script\b([^>]*)>([\s\S]*?)<\/script>/gi;
  let mt, balanced = true;
  while ((mt = re.exec(src))) {
    if (/\bsrc\s*=/.test(mt[1])) continue;
    const from = mt.index + mt[0].indexOf('>') + 1;
    const lx = lexJs(mt[2]);
    if (!lx.balanced) balanced = false;
    const c = lx.code.join('\n'), nc = lx.nocom.join('\n');
    for (let k = 0; k < mt[2].length; k++) { codeChars[from + k] = c[k]; nocomChars[from + k] = nc[k]; }
  }
  return { raw, code: codeChars.join('').split('\n'), nocom: nocomChars.join('').split('\n'), balanced };
}

