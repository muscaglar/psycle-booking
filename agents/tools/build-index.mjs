const IIFE_OPEN = /^\s*[;!+~-]?\s*\(\s*(?:async\s+)?(?:function\s*\*?\s*([\w$]*)\s*\(\s*([\w$]*)[^)]*\)|\(\s*([\w$]*)[^)]*\)\s*=>)\s*\{\s*$/;

// From the "(" at (line, col) in the code mask → the matching ")" ; returns the text between, comments dropped.
function parenText(lx, line, col, maxLines = 14) {
  let d = 0, out = '';
  for (let i = line; i < Math.min(lx.code.length, line + maxLines); i++) {
    const c = lx.code[i], raw = lx.nocom[i];
    for (let j = i === line ? col : 0; j < c.length; j++) {
      const ch = c[j];
      if (ch === '(' || ch === '[' || ch === '{') { d++; if (d === 1) continue; }
      else if (ch === ')' || ch === ']' || ch === '}') { d--; if (d === 0) return { text: squash(out), endLine: i, endCol: j }; }
      out += raw[j] === undefined ? ' ' : raw[j];
    }
    out += ' ';
  }
  return null;
}

function analyseJs(rel) {
  const src = read(rel);
  const raw = src.split('\n');
  const lx = lexJs(src);
  const L = raw.length;
  const info = { rel, raw, lx, lines: countLines(src), symbols: [], banners: [], pure: [], iifes: [], wholeFileIife: false, bytes: Buffer.byteLength(src) };

  // Top-level IIFEs: a declaration one level inside one counts as top level.
  const base = new Array(L).fill(null), iifeParam = new Array(L).fill('');
  for (let i = 0; i < L; i++) {
    if (lx.depth[i] !== 0 || lx.mode[i] !== 'code') continue;
    const mt = IIFE_OPEN.exec(lx.code[i]);
    if (!mt || lx.depth[i + 1] === 0) continue;
    const b = lx.depth[i + 1];
    let j = i + 1;
    while (j < L && lx.depth[j + 1] >= b) j++;
    for (let k = i + 1; k <= j && k < L; k++) { base[k] = b; iifeParam[k] = mt[2] || mt[3] || ''; }
    info.iifes.push({ line: i + 1, end: Math.min(j, L - 1) + 1, name: mt[1] || '' });
    info.symbols.push({ line: i + 1, end: Math.min(j, L - 1) + 1, kind: 'iife', name: mt[1] || '', params: '', comment: commentAbove(raw, i) });
    i = j;
  }
  const codeLines = raw.filter((l, i) => lx.mode[i] === 'code' && l.trim() && !/^\s*(\/\/|\/\*|\*)/.test(l)).length;
  const inIife = base.filter((b, i) => b !== null && lx.mode[i] === 'code' && raw[i].trim() && !/^\s*(\/\/|\/\*|\*)/.test(raw[i])).length;
  info.wholeFileIife = codeLines > 0 && info.iifes.length === 1 && inIife / codeLines > 0.9;
  info.iifeParam = info.wholeFileIife ? iifeParam.find((p) => p) || '' : '';
  info.symbols = info.symbols.filter((s) => s.name || (!info.wholeFileIife && s.end - s.line + 1 >= 10));

  const isTop = (i) => lx.mode[i] === 'code' && (lx.depth[i] === 0 || (base[i] !== null && lx.depth[i] === base[i]));
  const endOf = (i) => { let j = i; while (j < L - 1 && lx.depth[j + 1] > lx.depth[i]) j++; return j; };

  // Banners (top level only) and pure regions (anywhere).
  const open = {};
  for (let i = 0; i < L; i++) {
    if (lx.mode[i] !== 'code') continue;
    const pm = PURE_MARK.exec(raw[i]);
    if (pm) {
      const name = pm[1] || 'waitlist';
      const legacy = !pm[1];
      if (pm[3] === 'start') (open[name] = open[name] || []).push(i + 1);
      else if (open[name] && open[name].length) info.pure.push({ name, legacy, start: open[name].pop(), end: i + 1 });
      continue;
    }
    if (!isTop(i) || !/^\s*(\/\/|\/\*)/.test(raw[i])) continue;
    const stripped = stripCommentLine(raw[i]);
    if (RULE_ONLY.test(stripped)) {
      let title = null, close = -1;
      for (let k = i + 1; k < Math.min(L, i + 16); k++) {
        if (!raw[k].trim() && title === null) continue;
        const s = stripCommentLine(raw[k]);
        if (RULE_ONLY.test(s)) { close = k; break; }
        if (/\*\/\s*$/.test(raw[k]) && !s.trim()) { close = k; break; }
        if (title === null && s.trim()) title = s.trim();
        if (!/^\s*(\/\/|\*|\/\*)/.test(raw[k]) && lx.mode[k] === 'code') break;          // ran into code: not a box
      }
      if (title !== null && close !== -1) { info.banners.push({ line: i + 1, level: 2, title: tidy(title) }); i = close; }
      continue;
    }
    const t = bannerTitle(raw[i]);
    if (t !== null) info.banners.push({ line: i + 1, level: 3, title: tidy(t) });
  }
  info.pure.sort((a, b) => a.start - b.start || a.end - b.end);

  // Symbols.
  for (let i = 0; i < L; i++) {
    if (!isTop(i)) continue;
    const c = lx.code[i];
    const indent = c.length - c.trimStart().length;
    const t = c.trimStart();
    let mt;
    const sym = (o) => info.symbols.push(Object.assign({ line: i + 1, end: endOf(i) + 1, comment: commentAbove(raw, i) }, o));
    const paramsAt = (col) => { const p = parenText(lx, i, col); return p ? p.text : '…'; };
    if ((mt = /^(?:export\s+(?:default\s+)?)?(async\s+)?function\s*(\*)?\s*([\w$]+)\s*\(/.exec(t))) {
      sym({ kind: 'fn', name: mt[3], async: !!mt[1], params: paramsAt(indent + mt[0].length - 1) });
      continue;
    }
    if ((mt = /^(?:export\s+(?:default\s+)?)?class\s+([\w$]+)/.exec(t))) { sym({ kind: 'class', name: mt[1] }); continue; }
    const p = iifeParam[i];
    const exportRe = new RegExp('^(window|globalThis|self' + (p ? '|' + p.replace(/\$/g, '\\$') : '') + ')\\.([A-Za-z_$][\\w$]*)\\s*=(?![=>])\\s*');
    const declRe = /^(?:export\s+)?(const|let|var)\s+([A-Za-z_$][\w$]*)\s*(?:=(?![=>])\s*)?/;
    const isExport = exportRe.exec(t);
    const isDecl = isExport ? null : declRe.exec(t);
    if (!isExport && !isDecl) continue;
    const head = (isExport || isDecl)[0];
    const rhs = t.slice(head.length);
    const rhsCol = indent + head.length;
    const name = isExport ? isExport[1] + '.' + isExport[2] : isDecl[2];
    let fn = null;
    if ((mt = /^(async\s+)?function\b\s*\*?\s*[\w$]*\s*\(/.exec(rhs))) fn = { async: !!mt[1], params: paramsAt(rhsCol + mt[0].length - 1) };
    else if ((mt = /^(async\s+)?\(/.exec(rhs))) {
      const pt = parenText(lx, i, rhsCol + mt[0].length - 1);
      if (pt) {
        const after = lx.code[pt.endLine].slice(pt.endCol + 1) + ' ' + (lx.code[pt.endLine + 1] || '');
        if (/^\s*=>/.test(after)) fn = { async: !!mt[1], params: pt.text };
      }
    } else if ((mt = /^(async\s+)?([A-Za-z_$][\w$]*)\s*=>/.exec(rhs))) fn = { async: !!mt[1], params: mt[2] };
    if (fn) { sym({ kind: isExport ? 'export-fn' : 'fn', decl: isDecl ? isDecl[1] : '', name, async: fn.async, params: fn.params }); continue; }
    if (isExport) {
      const alias = /^([A-Za-z_$][\w$.]*)\s*;?\s*$/.exec(rhs);
      if (rhs.startsWith('{')) sym({ kind: 'export-obj', name, keys: objectKeys(lx, i, rhsCol) });
      else if (alias && !/^(null|true|false|undefined|NaN)$/.test(alias[1])) sym({ kind: 'export-alias', name, alias: alias[1], comment: '' });
      continue;                                                                           // other values: globals.md has them
    }
    const keys = rhs.startsWith('{') && /^[A-Z]/.test(name) && !/^[A-Z0-9_]+$/.test(name) ? objectKeys(lx, i, rhsCol) : null;
    let names = name;
    if (endOf(i) === i && !keys) {
      const more = splitTopLevel(t.slice(isDecl[0].length).replace(/;\s*$/, '')).slice(1)
        .map((part) => /^\s*([A-Za-z_$][\w$]*)\s*(?:=(?![=>])|$)/.exec(part)).filter(Boolean).map((m2) => m2[1]);
      if (more.length) names = [name, ...more].join(', ');
    }
    sym({ kind: 'var', decl: isDecl[1], name: names, keys });
  }
  info.symbols.sort((a, b) => a.line - b.line || (a.kind === 'iife' ? -1 : 1));
  for (const s of info.symbols) s.pure = [...new Set(info.pure.filter((r) => s.line >= r.start && s.line <= r.end).map((r) => r.name))];
  info.base = base;
  return info;
}

// Member names of an object literal that opens at (line, col): the keys one level in.
function objectKeys(lx, line, col) {
  const keys = [];
  let d = 0, seg = '';                                  // seg: the text of one member AT depth 1 (deeper text is skipped)
  for (let i = line; i < lx.code.length; i++) {
    const c = lx.code[i];
    for (let j = i === line ? col : 0; j < c.length; j++) {
      const ch = c[j];
      if (ch === '(' || ch === '[' || ch === '{') { d++; if (d === 2) seg += ch; continue; }
      if (ch === ')' || ch === ']' || ch === '}') { d--; if (d === 0) { pushKey(seg); return keys; } continue; }
      if (d !== 1) continue;
      if (ch === ',') { pushKey(seg); seg = ''; } else seg += ch;
    }
    seg += ' ';
  }
  return keys;
  function pushKey(text) {
    const mt = /^\s*(?:(?:async|get|set)\s+(?=[A-Za-z_$])|\*\s*)?([A-Za-z_$][\w$]*)\s*(?:[:(]|$)/.exec(text);
    if (mt && !keys.includes(mt[1])) keys.push(mt[1]);
  }
}

function enclosingSymbol(info, line) {
  let best = null;
  for (const s of info.symbols) {
    if (s.line <= line && s.end >= line && s.kind !== 'var' && (!best || s.line >= best.line)) best = s;
  }
  return best;
}

function enclosing(info, line) {
  const best = enclosingSymbol(info, line);
  return best ? best.name.replace(/^(window|globalThis|self)\./, '') : '';
}

