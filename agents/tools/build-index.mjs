function listFiles(dir, test) {
  if (!exists(dir)) return [];
  return fs.readdirSync(abs(dir), { withFileTypes: true })
    .filter((d) => d.isFile() && !d.name.startsWith('.') && test(d.name))
    .map((d) => dir + '/' + d.name)
    .sort(byName);
}

function walk(dir, test, skipDirs) {
  if (!exists(dir)) return [];
  const out = [];
  const visit = (rel) => {
    for (const d of fs.readdirSync(abs(rel), { withFileTypes: true })) {
      if (d.name.startsWith('.')) continue;
      const child = rel + '/' + d.name;
      if (d.isDirectory()) { if (!skipDirs.includes(d.name)) visit(child); }
      else if (d.isFile() && test(d.name)) out.push(child);
    }
  };
  visit(dir);
  return out.sort(byName);
}

