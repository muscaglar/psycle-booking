function firstComment(src) {
  const lines = src.split('\n');
  let i = 0;
  while (i < lines.length && (/^\s*$/.test(lines[i]) || /^\s*['"]use strict['"];?\s*$/.test(lines[i]) || /^#!/.test(lines[i]))) i++;
  const block = [];
  if (/^\s*\/\//.test(lines[i] || '')) { while (i < lines.length && /^\s*\/\//.test(lines[i])) block.push(stripCommentLine(lines[i++])); }
  else if (/^\s*\/\*/.test(lines[i] || '')) { while (i < lines.length) { block.push(stripCommentLine(lines[i])); if (/\*\//.test(lines[i++])) break; } }
  else if (/^\s*<!--/.test(lines[i] || '')) { while (i < lines.length) { block.push(lines[i].replace(/<!--|-->/g, '')); if (/-->/.test(lines[i++])) break; } }
  const text = [];
  for (const l of block) { if (RULE_ONLY.test(l)) continue; if (!l.trim() && text.length) break; text.push(l); }
  return tidy(firstSentence(text.join(' ')));
}

// A suite's opening line: its first sentence, cut where an enumerated list starts ("…: 1. …", "…: • …").
function suiteSummary(src) {
  return firstComment(src).replace(/\s*[:—–-]\s*(?:1\.|a\.|[•·*-])\s.*$/, '.').replace(/[.:]\.$/, '.');
}

// A quoted string as the suite wrote it → the text it stands for.
const unescapeJs = (lit) => lit.replace(/\\(n|t|'|"|`|\\)/g, (m, ch) => (ch === 'n' ? '\n' : ch === 't' ? '\t' : ch));
// What an anchor looks like: the start of a declaration, a comment or banner, or a line break to cut at.
const ANCHOR_SHAPE = /^(?:\n|\s*\/\/|\s*\/\*|\s*(?:async\s+)?function\b|\s*(?:window|globalThis)\.|\s*(?:const|let|var|class|struct|enum|extension|public|private|static|func)\s)/;

function analyseSuite(rel, jsInfos, sources = []) {
  const src = read(rel);
  const lx = lexJs(src);
  const nocom = lx.nocom.join('\n');
  const consts = new Map();
  let mt;
  const cre = /(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*(['"])([^'"]+\.(?:js|html|css))\2/g;
  while ((mt = cre.exec(nocom))) consts.set(mt[1], mt[3]);
  const pure = [];
  const lre = /loadPure\(\s*([^,()]+?)\s*,\s*(['"])([\w-]+)\2/g;
  while ((mt = lre.exec(nocom))) {
    const f = /^(['"])(.+)\1$/.exec(mt[1]);
    pure.push({ file: f ? f[2] : consts.get(mt[1]) || '*', name: mt[3] });
  }
  const mre = /(?:pure:([\w-]+)|(waitlist):pure):start/g;
  while ((mt = mre.exec(nocom))) { const name = mt[1] || 'waitlist'; if (!pure.some((p) => p.name === name)) pure.push({ file: '*', name }); }
  const known = new Set(jsInfos.flatMap((i) => i.pure.map((r) => r.name)));
  for (let k = pure.length - 1; k >= 0; k--) if (!known.has(pure[k].name)) pure.splice(k, 1);   // e.g. the harness's own 'no-such-block'
  const anchors = [];
  // 'function bookClass(' — or the whole opener, 'function _paintDayDot(pill, held) {'
  const are = /(['"`])\s*(?:async\s+)?function\s*\*?\s*([A-Za-z_$][\w$]*)\s*(?:\([\w$\s,={}.[\]]*\)?\s*\{?\s*)?\1/g;
  while ((mt = are.exec(nocom))) if (!anchors.includes(mt[2])) anchors.push(mt[2]);
  const wre = /(['"`])\s*window\.([A-Za-z_$][\w$]*)\s*=\s*(?:async\s+)?function[^'"`]*\1/g;
  while ((mt = wre.exec(nocom))) if (!anchors.includes(mt[2])) anchors.push(mt[2]);
  const checks = (nocom.match(/(?<![\w$])(?:t\.)?(?:ok|eq)\(/g) || []).length;
  // Text anchors: a string the suite holds that is, verbatim, a piece of shipped source shaped like the start of a
  // declaration or a banner — what `between(src, 'A', 'B')` and `src.indexOf('// ── A. Themes')` cut by.
  const textAnchors = new Map();
  const sre = /'((?:[^'\\\n]|\\.){10,160})'|"((?:[^"\\\n]|\\.){10,160})"/g;
  while ((mt = sre.exec(nocom))) {
    const text = unescapeJs(mt[1] !== undefined ? mt[1] : mt[2]);
    if (!ANCHOR_SHAPE.test(text) || /^\s*\/\/\s*──\s*(?:pure:[\w-]+|waitlist:pure)/.test(text) || /^\s*(?:async\s+)?function\s*\*?\s*[\w$]+\s*\(?[^)]*\)?\s*\{?\s*$/.test(text)) continue;
    const home = sources.find((f) => f.text.indexOf(text) !== -1);
    if (!home) continue;
    if (!textAnchors.has(home.rel)) textAnchors.set(home.rel, []);
    const shown = text.replace(/\n/g, '⏎').trim();
    if (!textAnchors.get(home.rel).includes(shown)) textAnchors.get(home.rel).push(shown);
  }
  for (const [file, texts] of textAnchors) textAnchors.set(file, texts.filter((x) => !texts.some((y) => y !== x && y.indexOf(x) === 0)));   // 'var TAB_ICONS' next to 'var TAB_ICONS = {'
  const byFile = new Map();
  for (const a of anchors) {
    const home = jsInfos.find((i) => i.symbols.some((s) => s.name === a || s.name === 'window.' + a));
    const key = home ? home.rel : '(not a top-level symbol)';
    if (!byFile.has(key)) byFile.set(key, []);
    byFile.get(key).push(a);
  }
  return { rel, lines: countLines(src), summary: suiteSummary(src), pure, anchors: byFile, textAnchors, checks };
}

