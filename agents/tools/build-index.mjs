const SWIFT_UI_TYPE = /:\s*[^{]*\b(?:View|Widget|WidgetBundle|WidgetConfiguration|Shape|ViewModifier|ButtonStyle|TimelineProvider|TimelineEntry|AppIntent|AppShortcutsProvider|App|PreviewProvider|CAPPlugin|CAPBridgedPlugin|CAPBridgeViewController|UIResponder|UIViewController|UIWindowSceneDelegate|NSObject)\b/;
const SWIFT_PROP = /^\s*(?:@[\w.]+(?:\([^)]*\))?\s+)*(?:(?:public|private|fileprivate|internal|static|final|lazy|weak|nonisolated)(?:\(set\))?\s+)*(let|var)\s+([A-Za-z_]\w*)\s*(?::\s*([^={]+))?\s*[={]?/;

function analyseSwift(rel) {
  const src = read(rel);
  const raw = src.split('\n');
  const lx = lexSwift(src);
  const items = [];
  const typeRe = /^\s*(?:@[\w.]+(?:\([^)]*\))?\s+)*(?:(?:public|private|fileprivate|internal|open|final|static|indirect|nonisolated)\s+)*(class|struct|enum|protocol|extension|actor)\s+([\w.]+)/;
  const funcRe = /^\s*(?:@[\w.]+(?:\([^)]*\))?\s+)*(?:(?:public|private|fileprivate|internal|open|final|static|class|override|mutating|nonisolated|convenience|required)\s+)*(func\s+[\w]+|init\??)\s*[(<]/;
  for (let i = 0; i < raw.length; i++) {
    const c = lx.code[i];
    const d = lx.depth[i];
    let mt;
    if ((mt = typeRe.exec(c)) && !/^\s*(?:(?:public|private|static|final|override)\s+)*class\s+(?:func|var|let)\b/.test(c)) {
      const item = { line: i + 1, depth: d, text: squash(raw[i].replace(/\s*\{\s*$/, '')) };
      items.push(item);
      // The properties of a VALUE type are its shape — for a Codable one, a compatibility contract with payloads an
      // older build wrote. Views, widgets, intents and delegates are left out: their properties are wiring.
      if (/^(struct|class|actor)$/.test(mt[1]) && !SWIFT_UI_TYPE.test(c)) {
        const stored = [], computed = [];
        for (let k = i + 1; k < raw.length && lx.depth[k] > d; k++) {
          if (lx.depth[k] !== d + 1) continue;
          const pm = SWIFT_PROP.exec(lx.code[k]);
          if (!pm) continue;
          const type = squash((pm[3] || '').replace(/\s*[={].*$/, ''));
          const label = pm[2] + (type ? ': ' + type : '');
          if (pm[1] === 'var' && /\{\s*$|\{\s*(?:get|return|[\w.(])/.test(lx.code[k].slice(pm.index + pm[0].length - 1)) && !/=/.test(pm[0])) computed.push(label); else stored.push(label);
        }
        if (stored.length) item.stored = stored;
        if (computed.length) item.computed = computed;
      }
    } else if (d <= 1 && (mt = funcRe.exec(c))) {
      items.push({ line: i + 1, depth: d, text: squash(raw[i].replace(/\s*\{\s*$/, '')) });
    }
  }
  return { rel, lines: countLines(src), items, summary: firstComment(src).replace(/^\S+\.swift\s+/, '') };
}

