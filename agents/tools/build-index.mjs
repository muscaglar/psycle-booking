  // Script load order: an inline script of a shell first, then the <script src> order, then what the page never lists
  // (the iOS build appends native-bridge.js last; sw.js is its own world).
  const rank = (file) => { if (/\.html$/.test(file)) return -1; const k = loadOrder.indexOf(file); return k === -1 ? (file === 'sw.js' ? 999 : 998) : k; };
