function symbolLine(s, width) {
  let label;
  if (s.kind === 'iife') label = '(iife) ' + (s.name ? s.name + '()' : '(anonymous)');
  else if (s.kind === 'class') label = 'class ' + s.name;
  else if (s.kind === 'var') label = s.decl + ' ' + s.name;
  else if (s.kind === 'export-obj') label = s.name + ' = {…}';
  else if (s.kind === 'export-alias') label = s.name + ' = ' + s.alias;
  else label = (s.async ? 'async ' : '') + s.name + '(' + clip(s.params, 90) + ')';
  const len = s.end - s.line + 1;
  let out = 'L' + s.line + '  ' + label;
  if (len >= 30) out += '  +' + len;
  if (s.pure && s.pure.length) out += '  {' + s.pure.join(',') + '}';
  let note = s.comment || '';
  if (s.keys && s.keys.length) note = 'keys: ' + s.keys.slice(0, 30).join(', ') + (s.keys.length > 30 ? ', …' : '') + (note ? ' — ' + note : '');
  if (note && width > 0) out += '  — ' + (s.keys && s.keys.length ? clip(note, Math.max(width, 200)) : clip(note, width));
  return out;
}

function renderSymbols(info) {
  const items = [
    ...info.banners.map((b) => ({ line: b.line, heading: b })),
    ...info.symbols.map((s) => ({ line: s.line, symbol: s })),
  ].sort((a, b) => a.line - b.line || (a.heading ? -1 : 1));
  const kept = items.filter((it, idx) => {
    if (!it.heading) return true;
    const next = items[idx + 1];
    return !!next && !(next.heading && next.heading.level <= it.heading.level);
  });
  const shape = info.wholeFileIife
    ? 'The whole file is one IIFE: what is listed are the declarations one level inside it.'
    : info.iifes.length ? 'Top level, plus the declarations one level inside its top-level IIFEs.' : 'Top level only.';
  const build = (width) => [
    '# ' + info.rel + ' — symbols',
    'Purpose: the shape of `' + info.rel + '` — every top-level function, class, variable and `window.x` export, in source order under the file\'s own banners, with its line. Read this when you need to find code by what it DOES, or to see how the file is laid out. Skip it when you know the exact name — `grep -n` on the source is as cheap.',
    '',
    HEADER_SLOT,
    '',
    info.lines + ' lines · ' + info.symbols.length + ' symbols. ' + shape + ' Format: `L<line>  name(params)  +<length in lines, when 30 or more>  {pure blocks it sits in}  — first sentence of its comment`. Members of objects and functions nested in functions are not listed.',
    '',
    ...kept.map((it) => (it.heading ? '\n' + '#'.repeat(it.heading.level) + ' ' + clip(it.heading.title, 110) + ' (L' + it.heading.line + ')' : symbolLine(it.symbol, width))),
    '',
  ].join('\n');
  for (const w of COMMENT_WIDTHS) {
    const text = build(w);
    if (Buffer.byteLength(text) <= SYMBOLS_BUDGET || w === 0) return text;
  }
  return build(0);
}

const HEADER_SLOT = '\u0000HEADER\u0000';

// Where the prose about a topic lives: the first of `candidates` that exists when the index is built — a file, or a
// heading inside one ("CLAUDE.md#Design System"). Never a dead pointer: with none present it says nothing.
function seeAlso(label, candidates) {
  for (const c of candidates) {
    const [file, heading] = c.split('#');
    if (!exists(file)) continue;
    if (heading && !new RegExp('^#{1,6} ' + heading.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'm').test(read(file))) continue;
    return ' ' + label + ': ' + file + (heading ? ' → "' + heading + '"' : '') + '.';
  }
  return '';
}

function doc(title, purpose, bodyLines) {
  return ['# ' + title, purpose, '', HEADER_SLOT, '', ...bodyLines, ''].join('\n');
}

