function sourceStamp() {
  try {
    const head = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: ROOT, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
    const dirty = execFileSync('git', ['status', '--porcelain', '--', ...INPUT_PATHS.filter(exists)], { cwd: ROOT, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
    return dirty ? 'working tree (uncommitted changes on top of `' + head + '`)' : '`' + head + '`';
  } catch (e) {
    return 'an unversioned copy (not a git checkout)';
  }
}

