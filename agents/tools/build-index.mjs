const RULE_CHARS = '─═=\\-';
const RULE_ONLY = new RegExp('^[' + RULE_CHARS + '\\s]*[' + RULE_CHARS + ']{8,}[' + RULE_CHARS + '\\s]*$');
const PURE_MARK = /^\s*\/\/\s*──\s*(?:pure:([\w-]+)|(waitlist):pure):(start|end)\b/;
const squash = (s) => s.replace(/\s+/g, ' ').trim();
const clip = (s, w) => (s.length <= w ? s : s.slice(0, Math.max(0, w - 1)).replace(/\s+\S*$/, '') + '…');

// Comment prose is quoted from the source; project-management asides in it are not useful to a reader of the index.
function tidy(s) {
  const body = squash(s)
    .replace(/\s*\((?:since\s+)?wave[\s-]*\d[^)]*\)/gi, '')
    .replace(/\s+by (?:an earlier|that) wave's verifier/gi, '');
  const t = body
    .replace(/^wave[\s-]*\d[\w.]*(?:\s*\([^)]*\))?\s*[—–:-]\s*/i, '')
    .replace(/^wave[\s-]*\d[\w.]*\s+/i, '');
  return squash(t !== body && t ? t[0].toUpperCase() + t.slice(1) : t);   // a stripped lead-in leaves a lower-case start
}

function stripCommentLine(l) {
  return l.replace(/^\s*\/\/+\s?/, '').replace(/^\s*\/\*+\s?/, '').replace(/\s*\*+\/\s*$/, '').replace(/^\s*\*+\s?/, '').trimEnd();
}

function firstSentence(text) {
  const t = squash(text);
  const re = /[.!?](?=\s|$)/g;
  let mt;
  while ((mt = re.exec(t))) {
    const head = t.slice(0, mt.index + 1);
    if (/(?:\be\.g|\bi\.e|\bvs|\betc|\bcf|\bapprox|\bNo|\binc|\bmin|\bmax)\.$/i.test(head) && mt.index + 1 < t.length) continue;
    if (/\s\S\.$/.test(head) && mt.index + 1 < t.length) continue;                      // a single-letter "sentence" (A. B.)
    return head;
  }
  return t;
}

// The comment block that ends on the line directly above `i` (no blank line between), as prose.
function commentAbove(rawLines, i) {
  const block = [];
  let k = i - 1;
  if (k >= 0 && /\*\/\s*$/.test(rawLines[k]) && !/^\s*\/\//.test(rawLines[k])) {
    while (k >= 0) { block.unshift(rawLines[k]); if (/\/\*/.test(rawLines[k])) break; k--; }
    if (k < 0) return '';
    if (!/^\s*\/\*/.test(rawLines[k])) return '';                                        // a trailing /* … */ after code
  } else {
    while (k >= 0 && /^\s*\/\//.test(rawLines[k])) { block.unshift(rawLines[k]); k--; }
  }
  if (!block.length) return '';
  if (k <= 0) return '';                                                                 // the file's own header, not this symbol's
  const lines = block.map(stripCommentLine);
  let dropTitle = RULE_ONLY.test(lines[0]);
  const out = [];
  for (let j = 0; j < lines.length; j++) {
    const l = lines[j];
    if (RULE_ONLY.test(l)) continue;
    if (PURE_MARK.test(block[j])) { out.length = 0; continue; }
    if (bannerTitle(block[j]) !== null) { out.length = 0; continue; }                    // prose above a banner belongs to the banner
    if (dropTitle && l.trim()) { dropTitle = false; continue; }
    if (/^\s*@\w+/.test(l)) break;                                                       // JSDoc tags end the description
    if (/^\s*(eslint-|@ts-|istanbul |prettier-)/.test(l)) continue;
    out.push(l);
  }
  return tidy(firstSentence(out.join(' ')));
}

// "// ── Title ─────" (or "/* ── Title ── */") → "Title"; anything else → null.
function bannerTitle(rawLine) {
  if (PURE_MARK.test(rawLine)) return null;
  const mt = /^\s*(?:\/\/+|\/\*+)\s*(?:[─═]{2,}|={3,}|-{3,})\s*(.*?)\s*(?:\*\/)?\s*$/.exec(rawLine);
  if (!mt) return null;
  const title = mt[1].replace(new RegExp('[' + RULE_CHARS + '\\s]*(\\*/)?$'), '').replace(/\s*\*\/$/, '').trim();
  return /[A-Za-z]/.test(title) ? title : null;
}

// file:line lists, grouped per file: "js/app.js:12,40 · js/tabs.js:7"
function sites(list, withFn) {
  const perFile = new Map();
  for (const s of list) {
    if (!perFile.has(s.file)) perFile.set(s.file, []);
    perFile.get(s.file).push(s);
  }
  return [...perFile.entries()].map(([file, arr]) => {
    arr.sort((a, b) => a.line - b.line);
    if (!withFn) return file + ':' + [...new Set(arr.map((s) => s.line))].join(',');
    const runs = [];
    for (const s of arr) {
      const last = runs[runs.length - 1];
      if (last && last.fn === (s.fn || '')) { if (!last.lines.includes(s.line)) last.lines.push(s.line); } else runs.push({ fn: s.fn || '', lines: [s.line] });
    }
    return file + ':' + runs.map((r) => r.lines.join(',') + (r.fn ? ' ' + r.fn : '')).join('; ');
  }).join(' · ');
}

